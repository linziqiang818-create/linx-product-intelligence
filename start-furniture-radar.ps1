$ErrorActionPreference = 'Stop'

function Test-FurnitureRadarRunning {
    return $null -ne (Get-NetTCPConnection -LocalPort 3000 -State Listen -ErrorAction SilentlyContinue)
}

Set-Location $PSScriptRoot

if (Test-FurnitureRadarRunning) {
    Start-Process 'http://localhost:3000'
    exit 0
}

[Console]::OutputEncoding = [Text.Encoding]::UTF8
function Write-Message([int[]]$Characters, [ConsoleColor]$Color) {
    Write-Host (-join ($Characters | ForEach-Object { [char]$_ })) -ForegroundColor $Color
}

